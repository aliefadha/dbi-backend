const KategoriBarangGudangService = require("../services/kategoriBarangGudangService");  
  
class KategoriBarangGudangController {  
  static async create(req, res) {  
    try {  
      const kategoriBarangGudang = await KategoriBarangGudangService.create(req.body);  
      res.status(201).json({  
        success: true,  
        data: kategoriBarangGudang,  
        message: "created successfully",  
      });  
    } catch (error) {  
      res.status(400).json({  
        success: false,  
        data: null,  
        message: error.message,  
      });  
    }  
  }  
  
  static async getAll(req, res) {  
    try {  
      const kategoriBarangGudangs = await KategoriBarangGudangService.getAll();  
      res.status(200).json({  
        success: true,  
        data: kategoriBarangGudangs,  
        message: "retrieved successfully",  
      });  
    } catch (error) {  
      res.status(500).json({  
        success: false,  
        data: null,  
        message: error.message,  
      });  
    }  
  }  
  
  static async getById(req, res) {  
    try {  
      const kategoriBarangGudang = await KategoriBarangGudangService.getById(req.params.id);  
      if (!kategoriBarangGudang) {  
        return res.status(404).json({  
          success: false,  
          data: null,  
          message: "not found",  
        });  
      }  
      res.status(200).json({  
        success: true,  
        data: kategoriBarangGudang,  
        message: "retrieved successfully",  
      });  
    } catch (error) {  
      res.status(500).json({  
        success: false,  
        data: null,  
        message: error.message,  
      });  
    }  
  }  
  
  static async update(req, res) {  
    try {  
      const kategoriBarangGudang = await KategoriBarangGudangService.update(req.params.id, req.body);  
      if (!kategoriBarangGudang) {  
        return res.status(404).json({  
          success: false,  
          data: null,  
          message: "not found",  
        });  
      }  
      res.status(200).json({  
        success: true,  
        data: kategoriBarangGudang,  
        message: "updated successfully",  
      });  
    } catch (error) {  
      res.status(400).json({  
        success: false,  
        data: null,  
        message: error.message,  
      });  
    }  
  }  
  
  static async delete(req, res) {  
    try {  
      const deleted = await KategoriBarangGudangService.delete(req.params.id);  
      if (!deleted) {  
        return res.status(404).json({  
          success: false,  
          data: null,  
          message: "not found",  
        });  
      }  
      res.status(200).json({  
        success: true,  
        data: null,  
        message: "deleted successfully",  
      });  
    } catch (error) {  
      res.status(500).json({  
        success: false,  
        data: null,  
        message: error.message,  
      });  
    }  
  }  
}  
  
module.exports = KategoriBarangGudangController;  
